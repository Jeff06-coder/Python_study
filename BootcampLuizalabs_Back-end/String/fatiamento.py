nome = "Jefferson Camargo Coelho"

print(nome[0:9]) # Imprime os caracteres do índice 0 ao 8

print(nome[10:17]) # Imprime os caracteres do índice 10 ao 16   

print(nome[18:]) # Imprime os caracteres do índice 18 até o final da string

print(nome[3:10:5]) # Imprime os caracteres do índice 3 ao 9, pulando 5 dentretro dos caracteres

print(nome[::2]) # Imprime os caracteres do início ao fim, lendo a cada 2 caracteres

print(nome[::-1]) # Imprime os caracteres do início ao fim, lendo a cada 1 caractere, mas de trás para frente